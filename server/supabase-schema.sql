-- 5PLUS / Sarrif database schema for PostgreSQL (Supabase). The server also creates this by itself on first start;
-- this file is for reference or for creating the tables by hand (Supabase → SQL Editor → paste → Run).
CREATE TABLE public.conversations (
    id text NOT NULL,
    product_id text NOT NULL,
    buyer_id bigint NOT NULL,
    seller_id bigint NOT NULL,
    last_at bigint NOT NULL,
    buyer_read_at bigint DEFAULT 0 NOT NULL,
    seller_read_at bigint DEFAULT 0 NOT NULL
);
CREATE TABLE public.expenses (
    id text NOT NULL,
    date text NOT NULL,
    cur text NOT NULL,
    amount double precision NOT NULL,
    category text NOT NULL,
    note text DEFAULT ''::text NOT NULL,
    created_by bigint,
    created_at bigint NOT NULL,
    CONSTRAINT expenses_cur_check CHECK ((cur = ANY (ARRAY['USD'::text, 'SLSH'::text])))
);
CREATE TABLE public.files (
