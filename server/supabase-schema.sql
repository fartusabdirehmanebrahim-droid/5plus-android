CREATE TABLE public.products (
    id text NOT NULL,
    shop_id bigint NOT NULL,
    name text NOT NULL,
    description text DEFAULT ''::text NOT NULL,
    price double precision NOT NULL,
    cur text NOT NULL,
    mode text NOT NULL,
    images text DEFAULT '[]'::text NOT NULL,
    video text DEFAULT ''::text NOT NULL,
    comm_type text DEFAULT 'percent'::text NOT NULL,
    comm_value double precision DEFAULT 0 NOT NULL,
    hidden bigint DEFAULT 0 NOT NULL,
    admin_hidden bigint DEFAULT 0 NOT NULL,
    deleted bigint DEFAULT 0 NOT NULL,
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    service text DEFAULT 'suuq'::text NOT NULL,
    price_hidden bigint DEFAULT 0 NOT NULL,
    price_label text DEFAULT ''::text NOT NULL,
    country text DEFAULT ''::text NOT NULL,
    approval text DEFAULT 'approved'::text NOT NULL,
    review_note text DEFAULT ''::text NOT NULL,
    CONSTRAINT products_comm_type_check CHECK ((comm_type = ANY (ARRAY['percent'::text, 'flat'::text]))),
    CONSTRAINT products_cur_check CHECK ((cur = ANY (ARRAY['USD'::text, 'SLSH'::text]))),
    CONSTRAINT products_mode_check CHECK ((mode = ANY (ARRAY['buy'::text, 'book'::text])))
);
CREATE TABLE public.requests (
    id text NOT NULL,
    ref text NOT NULL,
    customer_id bigint NOT NULL,
    cur text NOT NULL,
    from_wallet text NOT NULL,
    from_num text NOT NULL,
    to_wallet text NOT NULL,
    to_num text NOT NULL,
    to_name text DEFAULT ''::text NOT NULL,
    amount double precision NOT NULL,
    fee double precision NOT NULL,
    receive double precision NOT NULL,
    ussd text,
    status text DEFAULT 'waiting'::text NOT NULL,
    acked bigint DEFAULT 0 NOT NULL,
    created_at bigint NOT NULL,
    sent_at bigint,
    sent_by bigint,
    proof text,
    CONSTRAINT requests_cur_check CHECK ((cur = ANY (ARRAY['USD'::text, 'SLSH'::text]))),
    CONSTRAINT requests_status_check CHECK ((status = ANY (ARRAY['waiting'::text, 'sent'::text])))
);
CREATE TABLE public.settings (
